// Developer-only secrets. local.properties is git-ignored. Keys are injected into DEBUG builds only:
// anything compiled into an APK can be extracted, so release builds must use the in-app
// (Keystore-encrypted) key field or, for public distribution, a backend proxy (see README).
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun localProp(name: String): String = (localProps.getProperty(name) ?: "").replace("\"", "")

// Optional release signing: create keystore.properties (storeFile, storePassword, keyAlias, keyPassword).
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "com.helper.voiceassistant"
    compileSdk = 37

    defaultConfig {
        applicationId = "com.helper.voiceassistant"
        minSdk = 26
        targetSdk = 37
        versionCode = 1
        versionName = "1.0.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        // sherpa-onnx ships native libs for 4 ABIs; real phones only need ARM.
        ndk { abiFilters += setOf("arm64-v8a", "armeabi-v7a") }
        buildConfigField("String", "DEV_DEEPSEEK_API_KEY", "\"\"")
    }

    // Exported Room schemas, read by MigrationTestHelper in the instrumentation tests.
    sourceSets {
        getByName("androidTest").assets.srcDir("$projectDir/schemas")
    }

    signingConfigs {
        if (keystoreProps.getProperty("storeFile") != null) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            buildConfigField("String", "DEV_DEEPSEEK_API_KEY", "\"${localProp("DEEPSEEK_API_KEY")}\"")
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            // Without keystore.properties the release APK is signed with the debug key so it can be
            // installed for testing. Never publish a debug-signed build.
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
    }

    packaging {
        resources.excludes += setOf("/META-INF/{AL2.0,LGPL2.1}", "META-INF/LICENSE*.md")
    }

    lint {
        abortOnError = true
        checkReleaseBuilds = true
    }
}

